"""Windows webcam inference demo. Press Q to quit. Requires owner_embedding.pt."""
import argparse
from pathlib import Path
import cv2
import torch
import torch.nn.functional as F
from PIL import Image
from facenet_pytorch import MTCNN, InceptionResnetV1

def main():
    p = argparse.ArgumentParser()
    p.add_argument("--embedding", type=Path, default=Path("data/owner_embedding.pt"))
    p.add_argument("--threshold", type=float, default=0.70)
    p.add_argument("--camera", type=int, default=0)
    args = p.parse_args()
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    detector = MTCNN(image_size=160, keep_all=False, device=device)
    model = InceptionResnetV1(pretrained="vggface2").eval().to(device)
    # Only load files generated by your own Colab session.
    owner = torch.load(args.embedding, map_location="cpu", weights_only=True)
    owner = F.normalize(owner.float().flatten(), dim=0)
    cap = cv2.VideoCapture(args.camera)
    if not cap.isOpened():
        raise SystemExit("Webcam unavailable. Check camera permissions.")
    frame_number = 0
    label = "Starting..."
    try:
        while True:
            ok, frame = cap.read()
            if not ok:
                break
            # Process every fifth frame to reduce CPU usage.
            if frame_number % 5 == 0:
                rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
                face = detector(Image.fromarray(rgb))
                if face is None:
                    label = "NO FACE"
                else:
                    with torch.no_grad():
                        vec = model(face.unsqueeze(0).to(device)).squeeze(0).cpu()
                    score = torch.dot(owner, F.normalize(vec, dim=0)).item()
                    label = f"{'OWNER' if score >= args.threshold else 'UNKNOWN'} {score:.2f}"
            cv2.putText(frame, label, (20, 45), cv2.FONT_HERSHEY_SIMPLEX,
                        1, (255, 255, 255), 2)
            cv2.imshow("Robot owner recognition (Q to quit)", frame)
            if cv2.waitKey(1) & 0xFF == ord("q"):
                break
            frame_number += 1
    finally:
        cap.release()
        cv2.destroyAllWindows()

if __name__ == "__main__":
    main()
